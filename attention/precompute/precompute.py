"""Precompute the real-GPT-2 data the attention explainer shows: src/attndata.js.

    python precompute/precompute.py        # a few seconds on CPU; needs the `gpt2` checkpoint (Hugging Face)

The toy model runs live in the browser (from ../gpt2-embeddings/src/model.js). This file only
covers GPT-2 small's own attention: every head's weights on a few texts, and a score per head for
three habits (look at the previous token, look where the current token came before, look at the
first token).
"""
import base64, json, pathlib
import numpy as np
import torch
from huggingface_hub import snapshot_download
from transformers import GPT2LMHeadModel, GPT2TokenizerFast

ROOT = pathlib.Path(__file__).resolve().parent.parent
try:
    SNAP = snapshot_download("gpt2", local_files_only=True)
except Exception:
    SNAP = snapshot_download("gpt2", allow_patterns=["*.json", "merges.txt", "model.safetensors"])
OUT = ROOT / "src" / "attndata.js"
EOT = 50256
tok = GPT2TokenizerFast.from_pretrained(SNAP)
model = GPT2LMHeadModel.from_pretrained(SNAP, attn_implementation="eager").eval()
L, H = model.config.n_layer, model.config.n_head
b64 = lambda a: base64.b64encode(np.ascontiguousarray(a).tobytes()).decode()


VAL = {}   # each layer's value vectors, caught on the way through
for l, blk in enumerate(model.transformer.h):
    blk.attn.c_attn.register_forward_hook(lambda mod, i, o, l=l: VAL.__setitem__(l, o[0, :, 2 * model.config.n_embd:].numpy()))


def run(ids):
    with torch.no_grad():
        o = model(torch.tensor([ids]), output_attentions=True)
    A = np.stack([a[0].numpy() for a in o.attentions])          # L, H, T, T
    p = torch.softmax(o.logits[0], -1).numpy()                   # T, vocab
    return A, p


def pack(A):
    """Each head's lower triangle (row t: positions 0..t), as bytes 0..255."""
    T = A.shape[-1]
    rows = [A[:, :, t, : t + 1] for t in range(T)]
    return b64(np.round(np.concatenate(rows, -1) * 255).clip(0, 255).astype(np.uint8))


def text(ids, extra=None):
    A, p = run(ids)
    d = {"ids": ids, "att": pack(A)}
    # GPT-2's chance of the token that really came next, at each position, and its top guess
    d["pNext"] = [round(float(p[t, ids[t + 1]]), 4) for t in range(len(ids) - 1)]
    d["top"] = [int(p[t].argmax()) for t in range(len(ids))]
    d["topP"] = [round(float(p[t].max()), 4) for t in range(len(ids))]
    return d, A


NAT = "My cat likes to sleep on the warm laptop, and my dog likes to play in the garden."
nat, A_nat = text([EOT] + tok.encode(NAT))
# how long each head's value vector at the first position is, against the average of the others
vn = np.stack([np.linalg.norm(VAL[l].reshape(len(nat["ids"]), H, -1), axis=-1) for l in range(L)])   # L, T, H
vratio = (vn[:, 0, :] / vn[:, 1:, :].mean(1))
nat_noeot, A_ne = text(tok.encode(NAT))
nat_noeot_first = A_ne[:, :, 1:, 0].mean(-1).ravel()

# 20 random everyday words (single tokens with a leading space), then the same 20 again
vocab = tok.get_vocab()
DICT = set(pathlib.Path("/usr/share/dict/words").read_text().split())   # whole English words only, not fragments like " emot"
words = sorted(t for t, i in vocab.items() if t.startswith("Ġ") and t[1:] in DICT and t[1:].islower() and 4 <= len(t) - 1 <= 7 and i < 12000)
rng = np.random.default_rng(5)
R = [vocab[w] for w in rng.choice(words, 20, replace=False)]
rep, A_rep = text([EOT] + R + R)

# per-head scores
T = len(nat["ids"])
prev = A_nat[:, :, np.arange(1, T), np.arange(0, T - 1)].mean(-1)
first = A_nat[:, :, 1:, 0].mean(-1)
n = len(R)   # in rep, position 1 + n + i holds R[i] again; the token after its first copy is at 2 + i
ind = np.mean([A_rep[:, :, 1 + n + i, 2 + i] for i in range(n - 1)], 0)

data = {
    "layers": L, "heads": H, "dHead": model.config.n_embd // H,
    "texts": {"nat": nat, "natNoEot": nat_noeot, "rep": rep},
    "repN": n,
    "firstNoEot": [round(float(x), 3) for x in nat_noeot_first],
    "score": {k: [round(float(x), 3) for x in v.ravel()] for k, v in {"prev": prev, "ind": ind, "first": first, "vratio": vratio}.items()},
}
OUT.write_text("// generated by precompute/precompute.py from GPT-2 small (openai-community/gpt2); do not edit\nconst ATTN = " + json.dumps(data, separators=(",", ":")) + ";\n")
print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size / 1e3:.0f} kB)")
top = lambda s, k=6: sorted(((v, f"{i // H}.{i % H}") for i, v in enumerate(data["score"][s])), reverse=True)[:k]
print("prev", top("prev")); print("ind", top("ind")); print("first>0.5:", sum(v > 0.5 for v in data["score"]["first"]))
sink = np.array(data["score"]["first"]) > 0.5
print("sink heads: median value ratio", np.median(np.array(data["score"]["vratio"])[sink]), "first>0.5 without eot:", sum(np.array(nat_noeot_first) > 0.5))
print("rep words:", [tok.decode([i]) for i in R])
print("acc copy1", np.mean([rep["top"][t] == rep["ids"][t + 1] for t in range(1, n)]), "copy2", np.mean([rep["top"][t] == rep["ids"][t + 1] for t in range(n + 1, 2 * n)]))
